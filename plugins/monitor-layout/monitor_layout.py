    def selection_changed(self, monitor: dict):
        self.disp_name.set_label(f"{monitor['name']} — {monitor.get('description', '')}")
        self.enable_sw.set_active(not monitor.get("disabled", False))

        modes_list = [m["label"] for m in monitor.get("availableModes", [])]
        self.res_drop.set_model(Gtk.StringList.new(modes_list))
        # Select matching mode
        cur_w, cur_h, cur_r = monitor["width"], monitor["height"], round(monitor["refreshRate"], 3)
        for idx, m in enumerate(monitor.get("availableModes", [])):
            if m["width"] == cur_w and m["height"] == cur_h and round(m["refreshRate"], 3) == cur_r:
                self.res_drop.set_selected(idx)
                break

        # Select matching scale
        cur_scale = monitor["scale"]
        for idx, s in enumerate(COMMON_SCALES):
            if math.isclose(s, cur_scale, rel_tol=0.01):
                self.scale_drop.set_selected(idx)
                break

        self.x_spin.set_value(monitor["x"])
        self.y_spin.set_value(monitor["y"])

    def on_enable_toggled(self, switch, state):
        mon = self.monitors[self.canvas.selected]
        mon["disabled"] = not state
        self.canvas.queue_draw()
        return False

    def on_mode_changed(self, dropdown, _param):
        idx = dropdown.get_selected()
        mon = self.monitors[self.canvas.selected]
        modes = mon.get("availableModes", [])
        if 0 <= idx < len(modes):
            mon["width"] = modes[idx]["width"]
            mon["height"] = modes[idx]["height"]
            mon["refreshRate"] = modes[idx]["refreshRate"]
            self.canvas.queue_draw()

    def on_scale_changed(self, dropdown, _param):
        idx = dropdown.get_selected()
        if 0 <= idx < len(COMMON_SCALES):
            mon = self.monitors[self.canvas.selected]
            old_w, _ = logical_size(mon)
            mon["scale"] = COMMON_SCALES[idx]
            new_w, _ = logical_size(mon)
            delta_w = new_w - old_w
            # If other monitors were positioned to the right of this monitor, shift them so they remain adjacent
            right_edge = mon["x"] + old_w
            for other in self.monitors:
                if other != mon and not other.get("disabled"):
                    if abs(other["x"] - right_edge) < 25:
                        other["x"] += delta_w
            self.canvas.queue_draw()

    def on_pos_changed(self, spin):
        mon = self.monitors[self.canvas.selected]
        mon["x"] = int(self.x_spin.get_value())
        mon["y"] = int(self.y_spin.get_value())
        self.canvas.queue_draw()

    def normalize(self):
        active = [m for m in self.monitors if not m.get("disabled")]
        if not active:
            return
        min_x = min(m["x"] for m in active)
        min_y = min(m["y"] for m in active)
        for m in self.monitors:
            m["x"] -= min_x
            m["y"] -= min_y

    def identify(self, _button):
        if is_niri():
            self.status.set_label("Display identification: numbers 1, 2, ... correspond to card numbers.")
        else:
            self.status.set_label("Display identification active.")

    def preview(self, _button):
        try:
            self.normalize()
            if is_niri():
                for m in self.monitors:
                    if m.get("disabled"):
                        run("niri", "msg", "output", m["name"], "off", check=False)
                        continue
                    run("niri", "msg", "output", m["name"], "on", check=False)
                    mode_str = f"{m['width']}x{m['height']}@{m['refreshRate']:.3f}"
                    run("niri", "msg", "output", m["name"], "mode", mode_str, check=False)
                    run("niri", "msg", "output", m["name"], "scale", str(m["scale"]), check=False)
                    run("niri", "msg", "output", m["name"], "position", "set", str(m["x"]), str(m["y"]), check=False)
            else:
                for m in self.monitors:
                    refresh = f'{m["refreshRate"]:.3f}'.rstrip("0").rstrip(".")
                    rule = f'{m["name"]},{m["width"]}x{m["height"]}@{refresh},{m["x"]}x{m["y"]},{m["scale"]:g}'
                    if m.get("transform"):
                        rule += f',transform,{m["transform"]}'
                    run("hyprctl", "keyword", "monitor", rule)
            self.status.set_label("Live preview applied successfully!")
            self.canvas.queue_draw()
        except Exception as exc:
            self.status.set_label(f"Preview failed: {exc}")

    def save(self, _button):
        try:
            self.normalize()
            if is_niri():
                # Write to settings-manager.kdl output section
                if NIRI_CONFIG.exists():
                    backup = NIRI_CONFIG.with_name(f"{NIRI_CONFIG.name}.bak.{int(time.time())}")
                    shutil.copy2(NIRI_CONFIG, backup)
                
                # Format output blocks
                out_rules = "\n".join(monitor_rule_niri(m) for m in self.monitors)
                # Read existing config and replace or append output rules
                content = NIRI_CONFIG.read_text() if NIRI_CONFIG.exists() else ""
                
                # Remove existing output "..." blocks
                cleaned = re.sub(r'output\s+"[^"]+"\s*\{[^}]*\}', '', content, flags=re.MULTILINE)
                new_content = cleaned.strip() + "\n\n// Display & Monitor Layouts\n" + out_rules + "\n"
                
                temp = NIRI_CONFIG.with_suffix(".kdl.tmp")
                temp.write_text(new_content)
                temp.replace(NIRI_CONFIG)
                self.preview(_button)
                run("amane", "ipc", "call", "monitors", "sync", check=False)
                self.status.set_label(f"Layout saved to {NIRI_CONFIG.name} and synced with Amane!")
            else:
                HYPR_CONFIG.parent.mkdir(parents=True, exist_ok=True)
                if HYPR_CONFIG.exists():
                    backup = HYPR_CONFIG.with_name(f"{HYPR_CONFIG.name}.bak.{int(time.time())}")
                    shutil.copy2(HYPR_CONFIG, backup)
                content = HEADER_HYPR + "\n".join(monitor_rule_hypr(m) for m in self.monitors) + "\n"
                temp = HYPR_CONFIG.with_suffix(".lua.tmp")
                temp.write_text(content)
                temp.replace(HYPR_CONFIG)
                run("hyprctl", "reload", check=False)
                self.status.set_label(f"Layout saved to {HYPR_CONFIG.name} and applied!")
        except Exception as exc:
            self.status.set_label(f"Save failed: {exc}")

    def reset(self, _button):
        self.monitors[:] = json.loads(json.dumps(self.original))
        self.canvas.selected = 0
        self.selection_changed(self.monitors[0])
        self.canvas.queue_draw()
        self.status.set_label("Reset to initial layout.")


