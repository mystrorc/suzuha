def load_monitors_niri() -> list[dict]:
    try:
        raw = json.loads(run("niri", "msg", "--json", "outputs").stdout)
    except Exception as exc:
        raise RuntimeError(f"Could not read outputs from Niri: {exc}") from exc

    monitors = []
    for name, item in raw.items():
        modes = []
        for m in item.get("modes", []):
            rate = m["refresh_rate"] / 1000.0
            modes.append({
                "width": m["width"],
                "height": m["height"],
                "refreshRate": rate,
                "label": f"{m['width']} × {m['height']}  @  {rate:g} Hz"
            })
        modes.sort(key=lambda m: (m["width"] * m["height"], m["refreshRate"]), reverse=True)

        logical = item.get("logical")
        if logical:
            x = int(logical.get("x", 0))
            y = int(logical.get("y", 0))
            scale = float(logical.get("scale", 1.0))
            trans_str = str(logical.get("transform", "normal")).lower()
            trans_map = {"normal": 0, "90": 1, "180": 2, "270": 3}
            trans_val = trans_map.get(trans_str, 0)
            cur_mode_idx = item.get("current_mode")
            if cur_mode_idx is not None and cur_mode_idx < len(modes):
                w = modes[cur_mode_idx]["width"]
                h = modes[cur_mode_idx]["height"]
                r = modes[cur_mode_idx]["refreshRate"]
            elif modes:
                w, h, r = modes[0]["width"], modes[0]["height"], modes[0]["refreshRate"]
            else:
                w, h, r = 1920, 1080, 60.0
        else:
            x, y, scale, trans_val = 0, 0, 1.0, 0
            if modes:
                w, h, r = modes[0]["width"], modes[0]["height"], modes[0]["refreshRate"]
            else:
                w, h, r = 1920, 1080, 60.0

        make = item.get('make', '') or ''
        model = item.get('model', '') or ''
        serial = item.get('serial', '') or ''
        ident_parts = [make, model, serial]
        ident = " ".join(p for p in ident_parts if p).strip()

        monitors.append({
            "name": name,
            "ident": ident or name,
            "description": f"{make} {model}".strip() or name,
            "width": w,
            "height": h,
            "refreshRate": r,
            "availableModes": modes,
            "x": x,
            "y": y,
            "scale": scale,
            "transform": trans_val,
            "focused": False,
            "disabled": logical is None,
        })

    if not monitors:
        raise RuntimeError("Niri reported no monitors.")
    return monitors


def load_monitors_hyprland() -> list[dict]:
    try:
        raw = json.loads(run("hyprctl", "monitors", "all", "-j").stdout)
    except (FileNotFoundError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"Could not read monitors from Hyprland: {exc}") from exc

    monitors = []
    for item in raw:
        if item.get("disabled"):
            continue
        modes = parse_modes(item.get("availableModes", []))
        current_width = int(item.get("width", 1920))
        current_height = int(item.get("height", 1080))
        current_refresh = float(item.get("refreshRate", 60.0))
        best_mode = max(modes, key=lambda mode: (mode["width"] * mode["height"], mode["refreshRate"]), default=None)
        if best_mode:
            current_width = best_mode["width"]
            current_height = best_mode["height"]
            current_refresh = best_mode["refreshRate"]
        monitors.append({
            "name": item["name"],
            "description": item.get("description") or item["name"],
            "width": current_width,
            "height": current_height,
            "refreshRate": current_refresh,
            "availableModes": modes,
            "x": int(item.get("x", 0)),
            "y": int(item.get("y", 0)),
            "scale": float(item.get("scale", 1.0)),
            "transform": int(item.get("transform", 0)),
            "focused": bool(item.get("focused", False)),
            "disabled": False,
        })
    if not monitors:
        raise RuntimeError("Hyprland reported no enabled monitors.")
    return monitors


MODE_PATTERN = re.compile(r"^(\d+)x(\d+)@([0-9.]+)(?:Hz)?$")


def parse_modes(raw_modes: list[str]) -> list[dict]:
    modes = []
    seen = set()
    for raw_mode in raw_modes:
        match = MODE_PATTERN.match(str(raw_mode).strip())
        if not match:
            continue
        width, height = int(match.group(1)), int(match.group(2))
        refresh = float(match.group(3))
        key = (width, height, round(refresh, 3))
        if key in seen:
            continue
        seen.add(key)
        modes.append({
            "width": width,
            "height": height,
            "refreshRate": refresh,
            "label": f"{width} × {height}  @  {refresh:g} Hz",
        })
    modes.sort(key=lambda mode: (mode["width"] * mode["height"], mode["refreshRate"]), reverse=True)
    return modes


def logical_size(monitor: dict) -> tuple[int, int]:
    width, height = monitor["width"], monitor["height"]
    if monitor.get("transform", 0) in (1, 3, 5, 7):
        width, height = height, width
    scale = max(0.1, monitor["scale"])
    return round(width / scale), round(height / scale)


def monitor_rule_hypr(monitor: dict) -> str:
    refresh = f'{monitor["refreshRate"]:.3f}'.rstrip("0").rstrip(".")
    mode = f'{monitor["width"]}x{monitor["height"]}@{refresh}'
    scale = f'{monitor["scale"]:g}'
    parts = [
        f'output = "{monitor["name"]}"',
        f'mode = "{mode}"',
        f'position = "{monitor["x"]}x{monitor["y"]}"',
        f'scale = {scale}',
    ]
    if monitor["transform"]:
        parts.append(f'transform = {monitor["transform"]}')
    return "hl.monitor({ " + ", ".join(parts) + " })"


def monitor_rule_niri(monitor: dict) -> str:
    name = monitor["name"]
    is_internal = name.startswith("eDP")
    target_name = name if is_internal else (monitor.get("ident") or name)

    if monitor.get("disabled"):
        return f'output "{target_name}" {{\n    off\n}}'

    trans_map = {0: "normal", 1: "90", 2: "180", 3: "270"}
    trans = trans_map.get(monitor.get("transform", 0), "normal")
    return (
        f'output "{target_name}" {{\n'
        f'    mode "{monitor["width"]}x{monitor["height"]}@{monitor["refreshRate"]:.3f}"\n'
        f'    position x={monitor["x"]} y={monitor["y"]}\n'
        f'    scale {monitor["scale"]:.2f}\n'
        f'    transform "{trans}"\n'
        f'}}'
    )
class LayoutCanvas(Gtk.DrawingArea):
    PADDING = 34
    SNAP_PIXELS = 18
    ALIGN_PIXELS = 18

    def __init__(self, monitors: list[dict], changed_callback):
        super().__init__()
        self.monitors = monitors
        self.changed_callback = changed_callback
        self.selected = 0
        self.drag_origin = None
        self.drag_scale = None
        self.set_content_width(760)
        self.set_content_height(420)
        self.set_hexpand(True)
        self.set_vexpand(True)
        self.set_draw_func(self.draw)

        click = Gtk.GestureClick.new()
        click.connect("pressed", self.on_pressed)
        click.connect("released", self.on_released)
        self.add_controller(click)

        drag = Gtk.GestureDrag.new()
        drag.connect("drag-begin", self.on_drag_begin)
        drag.connect("drag-update", self.on_drag_update)
        drag.connect("drag-end", self.on_drag_end)
        self.add_controller(drag)

    def bounds(self):
        active = self.monitors
        if not active:
            return 0, 0, 1920, 1080
        left = min(m["x"] for m in active)
        top = min(m["y"] for m in active)
        right = max(m["x"] + logical_size(m)[0] for m in active)
        bottom = max(m["y"] + logical_size(m)[1] for m in active)
        return left, top, right, bottom

    def transform(self, width, height):
        left, top, right, bottom = self.bounds()
        scale = min(
            (width - self.PADDING * 2) / max(1, right - left),
            (height - self.PADDING * 2) / max(1, bottom - top),
        )
        scale = min(scale, 0.22)
        ox = (width - (right - left) * scale) / 2 - left * scale
        oy = (height - (bottom - top) * scale) / 2 - top * scale
        return scale, ox, oy

    def rect_for(self, monitor, width=None, height=None):
        width = width or self.get_width()
        height = height or self.get_height()
        scale, ox, oy = self.transform(width, height)
        lw, lh = logical_size(monitor)
        return monitor["x"] * scale + ox, monitor["y"] * scale + oy, lw * scale, lh * scale

    def monitor_at(self, x, y):
        for index in range(len(self.monitors) - 1, -1, -1):
            rx, ry, rw, rh = self.rect_for(self.monitors[index])
            if rx <= x <= rx + rw and ry <= y <= ry + rh:
                return index
        return None

    def draw(self, area, cr, width, height):
        cr.set_source_rgb(*rgb(THEME["dark_background"]))
        cr.paint()

        scale, ox, oy = self.transform(width, height)
        grid_step = 200 * scale
        cr.set_source_rgb(*rgb(THEME["selection"]))
        cr.set_line_width(1)
        x = ox % grid_step
        while x < width:
            cr.move_to(x, 0)
            cr.line_to(x, height)
            x += grid_step
        y = oy % grid_step
        while y < height:
            cr.move_to(0, y)
            cr.line_to(width, y)
            y += grid_step
        cr.stroke()

        for index, monitor in enumerate(self.monitors):
            rx, ry, rw, rh = self.rect_for(monitor, width, height)
            selected = index == self.selected
            disabled = monitor.get("disabled", False)

            cr.rectangle(rx, ry, rw, rh)
            if disabled:
                cr.set_source_rgb(*rgb(THEME["dark_background"]))
            elif selected:
                cr.set_source_rgb(*rgb(THEME["lighter_background"]))
            else:
                cr.set_source_rgb(*rgb(THEME["background"]))
            cr.fill_preserve()

            cr.set_line_width(3 if selected else 1.5)
            if disabled:
                cr.set_source_rgb(*rgb(THEME["dark_foreground"]))
            elif selected:
                cr.set_source_rgb(*rgb(THEME["accent"]))
            else:
                cr.set_source_rgb(*rgb(THEME["selection"]))
            cr.stroke()

            # Center tag
            tag = f"{index + 1}"
            cr.set_font_size(min(rw, rh) * 0.35)
            extents = cr.text_extents(tag)
            cr.move_to(rx + (rw - extents.width) / 2 - extents.x_bearing,
                       ry + (rh - extents.height) / 2 - extents.y_bearing)
            if disabled:
                cr.set_source_rgb(*rgb(THEME["dark_foreground"]))
            elif selected:
                cr.set_source_rgb(*rgb(THEME["accent"]))
            else:
                cr.set_source_rgb(*rgb(THEME["foreground"]))
            cr.show_text(tag)

            # Label banner
            banner_h = max(20, min(rh * 0.25, 34))
            cr.rectangle(rx, ry, rw, banner_h)
            cr.set_source_rgb(*rgb(THEME["dark_background"]))
            cr.fill()

            name = monitor["name"]
            cr.set_font_size(max(11, banner_h * 0.45))
            text_ext = cr.text_extents(name)
            cr.move_to(rx + 8, ry + (banner_h - text_ext.height) / 2 - text_ext.y_bearing)
            cr.set_source_rgb(*rgb(THEME["accent"] if selected else THEME["foreground"]))
            cr.show_text(name)

    def on_pressed(self, gesture, n_press, x, y):
        index = self.monitor_at(x, y)
        if index is not None:
            self.selected = index
            self.queue_draw()
            self.changed_callback(self.monitors[index])

    def on_released(self, gesture, n_press, x, y):
        pass

    def on_drag_begin(self, gesture, x, y):
        index = self.monitor_at(x, y)
        if index is not None:
            self.selected = index
            self.drag_origin = (self.monitors[index]["x"], self.monitors[index]["y"])
            scale, _, _ = self.transform(self.get_width(), self.get_height())
            self.drag_scale = scale
            self.queue_draw()
            self.changed_callback(self.monitors[index])
        else:
            self.drag_origin = None

    def on_drag_update(self, gesture, dx, dy):
        if not self.drag_origin or not self.drag_scale:
            return
        orig_x, orig_y = self.drag_origin
        new_x = orig_x + round(dx / self.drag_scale)
        new_y = orig_y + round(dy / self.drag_scale)

        monitor = self.monitors[self.selected]
        mw, mh = logical_size(monitor)

        # Snap to edges of other monitors
        snap_range = round(self.SNAP_PIXELS / self.drag_scale)
        for idx, other in enumerate(self.monitors):
            if idx == self.selected or other.get("disabled"):
                continue
            ox, oy = other["x"], other["y"]
            ow, oh = logical_size(other)

            # Snap X: right edge to left edge, or left edge to right edge
            if abs(new_x - (ox + ow)) < snap_range:
                new_x = ox + ow
            elif abs((new_x + mw) - ox) < snap_range:
                new_x = ox - mw

            # Snap Y: bottom edge to top edge, or top edge to bottom edge
            if abs(new_y - (oy + oh)) < snap_range:
                new_y = oy + oh
            elif abs((new_y + mh) - oy) < snap_range:
                new_y = oy - mh

            # Magnetic alignment (align tops, bottoms, or centers)
            if abs(new_y - oy) < snap_range:
                new_y = oy
            elif abs((new_y + mh) - (oy + oh)) < snap_range:
                new_y = oy + oh - mh
            elif abs((new_y + mh / 2) - (oy + oh / 2)) < snap_range:
                new_y = round(oy + oh / 2 - mh / 2)

            if abs(new_x - ox) < snap_range:
                new_x = ox
            elif abs((new_x + mw) - (ox + ow)) < snap_range:
                new_x = ox + ow - mw

        monitor["x"] = new_x
        monitor["y"] = new_y
        self.queue_draw()
        self.changed_callback(monitor)

    def on_drag_end(self, gesture, dx, dy):
        self.drag_origin = None
        self.drag_scale = None


