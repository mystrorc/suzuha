use amane::Color;

// a fixed palette that ignores the wallpaper
#[derive(Clone, Copy)]
pub struct Scheme {
    #[allow(dead_code)]
    pub name: &'static str,
    pub id: &'static str,
    pub light: bool,
    pub background: Color,
    pub surface: Color,
    pub hover_surface: Color,
    pub border: Color,
    pub text: Color,
    pub secondary_text: Color,
    pub muted_text: Color,
    pub accent: Color,
    pub accent_hover: Color,
    pub on_accent: Color,
    pub success: Color,
    pub danger: Color,
}

pub fn find(name: &str) -> Option<&'static Scheme> {
    if name == "gruvbox" {
        return find("gruvbox_dark");
    }
    SCHEMES.iter().find(|s| s.id == name)
}

