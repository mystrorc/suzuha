fn update_termusic_config(path: &str, theme: &Theme, colors: &Colors) {
    let Ok(existing) = fs::read_to_string(path) else {
        return;
    };

    let mut out: Vec<String> = Vec::new();
    let mut section = String::new();

    for line in existing.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') && trimmed.ends_with(']') {
            section = trimmed[1..trimmed.len() - 1].trim().to_string();
            out.push(line.to_string());
            continue;
        }

        if section.starts_with("style.") && trimmed.starts_with("background_color =") {
            out.push(String::from("background_color = \"Reset\""));
            continue;
        }

        let replacement = match (section.as_str(), trimmed.split('=').next().map(str::trim)) {
            ("theme", Some("name")) => Some(String::from("name = \"Amane\"")),
            ("theme.primary", Some("background")) => Some(format!("background = \"{}\"", hex(colors.background))),
            ("theme.primary", Some("foreground")) => Some(format!("foreground = \"{}\"", hex(colors.foreground))),
            ("theme.cursor", Some("text")) => Some(format!("text = \"{}\"", hex(theme.on_accent))),
            ("theme.cursor", Some("cursor")) => Some(format!("cursor = \"{}\"", hex(colors.cursor))),
            ("theme.normal", Some("black")) => Some(format!("black = \"{}\"", hex(colors.ansi[0]))),
            ("theme.normal", Some("red")) => Some(format!("red = \"{}\"", hex(colors.ansi[1]))),
            ("theme.normal", Some("green")) => Some(format!("green = \"{}\"", hex(colors.ansi[2]))),
            ("theme.normal", Some("yellow")) => Some(format!("yellow = \"{}\"", hex(colors.ansi[3]))),
            ("theme.normal", Some("blue")) => Some(format!("blue = \"{}\"", hex(colors.ansi[4]))),
            ("theme.normal", Some("magenta")) => Some(format!("magenta = \"{}\"", hex(colors.ansi[5]))),
            ("theme.normal", Some("cyan")) => Some(format!("cyan = \"{}\"", hex(colors.ansi[6]))),
            ("theme.normal", Some("white")) => Some(format!("white = \"{}\"", hex(colors.ansi[7]))),
            ("theme.bright", Some("black")) => Some(format!("black = \"{}\"", hex(colors.ansi[8]))),
            ("theme.bright", Some("red")) => Some(format!("red = \"{}\"", hex(colors.ansi[9]))),
            ("theme.bright", Some("green")) => Some(format!("green = \"{}\"", hex(colors.ansi[10]))),
            ("theme.bright", Some("yellow")) => Some(format!("yellow = \"{}\"", hex(colors.ansi[11]))),
            ("theme.bright", Some("blue")) => Some(format!("blue = \"{}\"", hex(colors.ansi[12]))),
            ("theme.bright", Some("magenta")) => Some(format!("magenta = \"{}\"", hex(colors.ansi[13]))),
            ("theme.bright", Some("cyan")) => Some(format!("cyan = \"{}\"", hex(colors.ansi[14]))),
            ("theme.bright", Some("white")) => Some(format!("white = \"{}\"", hex(colors.ansi[15]))),
            _ => None,
        };

        if let Some(rep) = replacement {
            out.push(rep);
        } else {
            out.push(line.to_string());
        }
    }

    let mut updated = out.join("\n");
    updated.push('\n');
    write(path, &updated);
}

fn kitty_config(theme: &Theme, colors: &Colors) -> String {
    let lines = [
        String::from("# generated by amane, do not edit"),
        format!("background {}", hex(colors.background)),
        format!("foreground {}", hex(colors.foreground)),
        format!("cursor {}", hex(colors.cursor)),
        format!("cursor_text_color {}", hex(theme.on_accent)),
        format!("selection_background {}", hex(colors.selection)),
        format!("selection_foreground {}", hex(colors.foreground)),
        format!("active_border_color {}", hex(colors.cursor)),
        format!("active_tab_background {}", hex(colors.cursor)),
        format!("active_tab_foreground {}", hex(theme.on_accent)),
        format!("inactive_tab_background {}", hex(colors.ansi[0])),
        format!("inactive_tab_foreground {}", hex(colors.ansi[8])),
        format!("tab_bar_background {}", hex(colors.ansi[0])),
    ];

    let mut text = lines.join("\n") + "\n";

    for (index, color) in colors.ansi.iter().enumerate() {
        text.push_str(&format!("color{index} {}\n", hex(*color)));
    }

    text
}

// the same colors under both of foot's themes, with the one in use picked
fn foot_config(theme: &Theme, colors: &Colors) -> String {
    let bare = |color: Color| hex(color).trim_start_matches('#').to_string();

    let initial = if theme.light { "light" } else { "dark" };

    let mut text = format!("# generated by amane, do not edit\n[main]\ninitial-color-theme={initial}\n");

    for section in ["dark", "light"] {
        text.push_str(&format!("[colors-{section}]\n"));
        text.push_str("alpha=0.75\n");
        text.push_str(&format!("background={}\n", bare(colors.background)));
        text.push_str(&format!("foreground={}\n", bare(colors.foreground)));
        text.push_str(&format!("selection-background={}\n", bare(colors.selection)));
        text.push_str(&format!("selection-foreground={}\n", bare(colors.foreground)));
        text.push_str(&format!("cursor={} {}\n", bare(colors.background), bare(colors.cursor)));
        text.push_str(&format!("urls={}\n", bare(colors.url)));

        for index in 0..8 {
            text.push_str(&format!("regular{index}={}\n", bare(colors.ansi[index])));
        }

        for index in 0..8 {
            text.push_str(&format!("bright{index}={}\n", bare(colors.ansi[index + 8])));
        }
    }

    text
}

// every kitty listens on a socket named after its pid
fn reload_kitty(path: &str) {
    let script = format!(
        "pgrep -x kitty >/dev/null 2>&1 || exit 0; \
         for pid in $(pgrep -x kitty); do \
         kitty @ --to unix:@amane-kitty-$pid set-colors --all --configured '{path}'; \
         done 2>/dev/null"
    );

    amane::spawn(&script);
}

/*
 * foot only reads its colors at startup, so running ones are switched to the
 * right theme by signal and sent the new colors as escape codes on their tty
 */
fn recolor_foot(theme: &Theme, colors: &Colors, folder: &str) {
    let osc = |code: &str, value: String| format!("\x1b]{code};{value}\x07");

    let mut codes = osc("10", hex(colors.foreground));

    codes.push_str(&osc("11", hex(colors.background)));
    codes.push_str(&osc("12", hex(colors.cursor)));
    codes.push_str(&osc("17", hex(colors.selection)));
    codes.push_str(&osc("19", hex(colors.foreground)));

    for (index, color) in colors.ansi.iter().enumerate() {
        codes.push_str(&osc("4", format!("{index};{}", hex(*color))));
    }

    let codes_path = format!("{folder}/terminal-colors-foot.osc");

    write(&codes_path, &codes);

    let signal = if theme.light { "-USR2" } else { "-USR1" };

    // Only scan /proc if foot is actually running
    let script = format!(
        "pgrep -x foot >/dev/null 2>&1 || exit 0; \
         pkill {signal} -x foot 2>/dev/null; sleep 0.05; seen=' '; \
         for environment in /proc/[0-9]*/environ; do \
         if tr '\\0' '\\n' 2>/dev/null < \"$environment\" | grep -qx 'TERM=foot'; then \
         process=${{environment%/environ}}; tty=$(readlink \"$process/fd/1\" 2>/dev/null); \
         case \"$tty\" in /dev/pts/[0-9]*) \
         case \"$seen\" in *\" $tty \"*) ;; *) \
         seen=\"$seen$tty \"; cat '{codes_path}' > \"$tty\" 2>/dev/null ;; esac ;; esac; fi; done"
    );

    amane::spawn(&script);
}
