use std::fs;

use amane::Color;

use super::{config_home, hex, state_home, write};
use crate::theme::{self, Theme};

// the seeds for the colors the shell's theme has no name for
const YELLOW: Color = Color::rgb(0xf9, 0xe2, 0xaf);
const MAGENTA: Color = Color::rgb(0xf5, 0xc2, 0xe7);
const CYAN: Color = Color::rgb(0x94, 0xe2, 0xd5);
const BLUE: Color = Color::rgb(0x89, 0xb4, 0xfa);

// the 16 ansi colors, and the few around them
struct Colors {
    background: Color,
    foreground: Color,
    selection: Color,
    cursor: Color,
    url: Color,
    ansi: [Color; 16],
}

// kitty, foot and alacritty color files, and the open terminals recolored on the spot
pub fn export(theme: &Theme) {
    let colors = colors(theme);

    let folder = state_home();

    let kitty = format!("{folder}/terminal-colors-kitty.conf");
    let foot = format!("{folder}/terminal-colors-foot.ini");
    let alacritty_state = format!("{folder}/terminal-colors-alacritty.toml");

    let alacritty_cfg = alacritty_config(theme, &colors);

    write(&kitty, &kitty_config(theme, &colors));
    write(&foot, &foot_config(theme, &colors));
    write(&alacritty_state, &alacritty_cfg);

    // Update active alacritty config: ~/.config/alacritty/amane-colors.toml
    let alacritty_conf = format!("{}/alacritty/amane-colors.toml", config_home());
    write(&alacritty_conf, &alacritty_cfg);

    // Update active ghostty theme: ~/.config/ghostty/theme-amane
    let ghostty_theme = format!("{}/ghostty/theme-amane", config_home());
    write(&ghostty_theme, &ghostty_config(theme, &colors));

    // Update termusic TUI config so it preserves terminal transparency ("Reset") and follows theme colors
    let termusic_conf = format!("{}/termusic/tui.toml", config_home());
    update_termusic_config(&termusic_conf, theme, &colors);

    reload_kitty(&kitty);
    recolor_foot(theme, &colors, &folder);
}

fn colors(theme: &Theme) -> Colors {
    let light = theme.light;

    // pulled toward the accent, so they sit with the rest of the theme
    let harmonize = |seed: Color, amount: f32| {
        let lightness = if light { 0.42 } else { 0.70 };

        theme::retone(theme::mix(seed, theme.accent, amount), lightness, 0.48)
    };

    // the dimmer first eight
    let regular = |color: Color| {
        let lightness = if light { 0.36 } else { 0.58 };

        theme::retone(color, lightness, 0.44)
    };

    let yellow = harmonize(YELLOW, 0.22);
    let magenta = harmonize(MAGENTA, 0.28);
    let cyan = harmonize(CYAN, 0.24);
    let blue = harmonize(BLUE, 0.30);

    Colors {
        background: theme.background,
        foreground: theme.text,
        selection: theme.selected_surface,
        cursor: theme.accent,
        url: blue,
        ansi: [
            theme.surface,
            regular(theme.danger),
            regular(theme.success),
            regular(yellow),
            regular(blue),
            regular(magenta),
            regular(cyan),
            theme.secondary_text,
            theme.muted_text,
            theme.danger,
            theme.success,
            yellow,
            blue,
            magenta,
            cyan,
            theme.text,
        ],
    }
}


fn ghostty_config(theme: &Theme, colors: &Colors) -> String {
    let mut out = format!(
        "# generated by amane, do not edit\n         background = {}\n         foreground = {}\n         cursor-color = {}\n         cursor-text = {}\n         selection-background = {}\n         selection-foreground = {}\n\n",
        hex(colors.background),
        hex(colors.foreground),
        hex(colors.cursor),
        hex(theme.on_accent),
        hex(colors.selection),
        hex(colors.foreground)
    );
    for (i, c) in colors.ansi.iter().enumerate() {
        out.push_str(&format!("palette = {}={}\n", i, hex(*c)));
    }
    out
}

