use std::fs;
use std::path::Path;

use amane::{Color, Service};

use super::{config_home, fill, hex, home, write};
use crate::settings::Settings;
use crate::theme::{self, Theme};

const TEMPLATE: &str = include_str!("flux.css");

const YELLOW: Color = Color::rgb(0xf9, 0xe2, 0xaf);

pub fn export(theme: &Theme) {
    let data = std::env::var("XDG_DATA_HOME").unwrap_or_else(|_| format!("{}/.local/share", home()));
    let config_dir = format!("{}/flux", config_home());
    let themes_dir = format!("{data}/flux/themes");

    let reduce_transparency = Settings::read().flag("reduce_transparency");

    let dark_css = stylesheet(&theme::for_mode(Some(false)), reduce_transparency);
    let light_css = stylesheet(&theme::for_mode(Some(true)), reduce_transparency);
    let active_css = stylesheet(theme, reduce_transparency);

    write(&format!("{themes_dir}/amane-dark.css"), &dark_css);
    write(&format!("{themes_dir}/amane-light.css"), &light_css);
    write(&format!("{config_dir}/style.css"), &active_css);

    let active_theme_name = if theme.light { "amane-light" } else { "amane-dark" };
    update_flux_config(&format!("{config_dir}/config.toml"), active_theme_name, theme);
    clear_cached_extension_icons(&format!("{data}/flux/icons/extensions"));
}

fn stylesheet(theme: &Theme, reduce_transparency: bool) -> String {
    let lightness = if theme.light { 0.42 } else { 0.70 };
    let yellow = theme::retone(theme::mix(YELLOW, theme.accent, 0.22), lightness, 0.48);

    let mantle = if theme.light {
        theme::mix(theme.background, Color::BLACK, 0.05)
    } else {
        theme::mix(theme.background, Color::BLACK, 0.22)
    };

    let (window_alpha, sidebar_alpha, card_alpha, popover_alpha) = if reduce_transparency {
        ("1.0", "1.0", "1.0", "1.0")
    } else {
        ("0.65", "0.45", "0.45", "0.88")
    };

    let names = [
        ("@BACKGROUND@", hex(theme.background)),
        ("@MANTLE@", hex(mantle)),
        ("@SURFACE@", hex(theme.surface)),
        ("@HOVER_SURFACE@", hex(theme.hover_surface)),
        ("@SELECTED_SURFACE@", hex(theme.selected_surface)),
        ("@ON_ACCENT@", hex(theme.on_accent)),
        ("@BORDER@", hex(theme.border)),
        ("@FOREGROUND@", hex(theme.text)),
        ("@MUTED@", hex(theme.secondary_text)),
        ("@ACCENT@", hex(theme.accent)),
        ("@RED@", hex(theme.danger)),
        ("@GREEN@", hex(theme.success)),
        ("@YELLOW@", hex(yellow)),
        ("@WINDOW_ALPHA@", String::from(window_alpha)),
        ("@SIDEBAR_ALPHA@", String::from(sidebar_alpha)),
        ("@CARD_ALPHA@", String::from(card_alpha)),
        ("@POPOVER_ALPHA@", String::from(popover_alpha)),
    ];

    format!("/* generated by amane, do not edit */\n{}", fill(TEMPLATE, &names))
}

fn update_flux_config(config_path: &str, theme_name: &str, theme: &Theme) {
    let Ok(existing) = fs::read_to_string(config_path) else {
        return;
    };

    let accent_hex = hex(theme.accent);
    let on_accent_hex = hex(theme.on_accent);
    let body_hex = hex(theme.surface);

    let mut lines: Vec<String> = Vec::new();
    let mut saw_theme = false;
    let mut saw_accent = false;

    for line in existing.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("theme =") {
            lines.push(format!("theme = \"{theme_name}\""));
            saw_theme = true;
        } else if trimmed.starts_with("auto_mime_accent_color =") {
            lines.push(format!("auto_mime_accent_color = \"{accent_hex}\""));
            saw_accent = true;
        } else if trimmed.starts_with("auto_mime_font_color =") {
            lines.push(format!("auto_mime_font_color = \"{on_accent_hex}\""));
        } else if trimmed.starts_with("auto_mime_body_color =") {
            lines.push(format!("auto_mime_body_color = \"{body_hex}\""));
        } else {
            lines.push(line.to_string());
        }
    }

    if !saw_theme {
        lines.push(format!("theme = \"{theme_name}\""));
    }
    if !saw_accent {
        lines.push(format!("auto_mime_accent_color = \"{accent_hex}\""));
    }

    let mut updated = lines.join("\n");
    updated.push('\n');
    write(config_path, &updated);
}

fn clear_cached_extension_icons(ext_dir: &str) {
    let path = Path::new(ext_dir);
    let Ok(entries) = fs::read_dir(path) else {
        return;
    };
    for entry in entries.flatten() {
        let p = entry.path();
        if p.extension().is_some_and(|e| e == "svg") {
            let _ = fs::remove_file(p);
        }
    }
}
