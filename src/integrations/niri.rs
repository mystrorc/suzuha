use std::fs;
use std::process::Command;

use amane::Service;

use super::{config_home, hex, write};
use crate::settings::Settings;
use crate::theme::Theme;

/*
 * Keeps Niri's window corner radius, clipping, shadows, gaps, and active/inactive
 * border colors synchronized with the shell's theme and Appearance settings.
 */
pub fn export(theme: &Theme) {
    let settings = Settings::read();

    let radius = settings.number("window_corner_radius").round() as u32;
    let border_width = settings.number("window_border_width").round() as u32;
    let inactive_border = settings.flag("window_inactive_border");
    let gaps = settings.number("window_gaps").round() as u32;
    let shadows = settings.flag("window_shadows");

    drop(settings);

    let accent = hex(theme.accent);
    let border = if inactive_border {
        hex(theme.border)
    } else {
        String::from("#00000000")
    };
    let urgent = hex(theme.danger);

    let border_toggle = if border_width == 0 { "off" } else { "on" };
    let shadow_toggle = if shadows { "on" } else { "off" };

    let kdl = format!(
        "// Generated by Swifty Shell — do not edit by hand\n\
         layout {{\n\
         \x20   gaps {gaps}\n\
         \x20   focus-ring {{\n\
         \x20       off\n\
         \x20   }}\n\
         \x20   border {{\n\
         \x20       {border_toggle}\n\
         \x20       width {border_width}\n\
         \x20       active-color \"{accent}\"\n\
         \x20       inactive-color \"{border}\"\n\
         \x20       urgent-color \"{urgent}\"\n\
         \x20   }}\n\
         \x20   shadow {{\n\
         \x20       {shadow_toggle}\n\
         \x20       softness 24\n\
         \x20       spread 4\n\
         \x20       offset x=0 y=4\n\
         \x20       color \"#00000055\"\n\
         \x20   }}\n\
         }}\n\n\
         window-rule {{\n\
         \x20   geometry-corner-radius {radius}\n\
         \x20   clip-to-geometry true\n\
         \x20   draw-border-with-background false\n\
         }}\n"
    );

    let niri_dir = format!("{}/niri", config_home());
    let window_kdl = format!("{niri_dir}/amane-window.kdl");
    let config_kdl = format!("{niri_dir}/config.kdl");

    let previous = fs::read_to_string(&window_kdl).unwrap_or_default();
    let changed = previous != kdl;

    if changed {
        write(&window_kdl, &kdl);
    }

    let includes_changed = ensure_includes_at_end(&config_kdl);

    if changed || includes_changed {
        let _ = Command::new("niri")
            .args(["msg", "action", "load-config-file"])
            .spawn();
    }
}

/*
 * In Niri's KDL parser, later blocks override earlier blocks. Ensure that
 * cursor.kdl, amane.kdl, and amane-window.kdl are included at the
 * very bottom of config.kdl rather than the top so they override defaults.
 */
fn ensure_includes_at_end(config_kdl: &str) -> bool {
    let Ok(existing) = fs::read_to_string(config_kdl) else {
        return false;
    };

    let managed = [
        "include \"cursor.kdl\"",
        "include \"amane.kdl\"",
        "include \"amane-window.kdl\"",
    ];

    let mut body: Vec<&str> = existing
        .lines()
        .filter(|line| {
            let trimmed = line.trim();
            !managed.contains(&trimmed)
        })
        .collect();

    while body.last().is_some_and(|line| line.trim().is_empty()) {
        body.pop();
    }

    let mut updated = body.join("\n");
    updated.push_str("\n\ninclude \"cursor.kdl\"\ninclude \"amane.kdl\"\ninclude \"amane-window.kdl\"\n");

    if updated != existing {
        write(config_kdl, &updated);
        true
    } else {
        false
    }
}
