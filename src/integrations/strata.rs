use std::fs;
use amane::{Color, Service};

use super::{config_home, hex, home, write};
use crate::settings::Settings;
use crate::theme::{self, Theme};

const YELLOW: Color = Color::rgb(0xf9, 0xe2, 0xaf);
const PURPLE: Color = Color::rgb(0xcb, 0xa6, 0xf7);
const PEACH: Color = Color::rgb(0xfa, 0xb3, 0x87);
const CYAN: Color = Color::rgb(0x89, 0xdc, 0xeb);

pub fn export(theme: &Theme) {
    let strata_dir = format!("{}/strata", config_home());
    let themes_dir = format!("{strata_dir}/themes");

    let harmonize = |seed: Color, amount: f32| {
        let lightness = if theme.light { 0.42 } else { 0.70 };
        theme::retone(theme::mix(seed, theme.accent, amount), lightness, 0.48)
    };

    let syntax_keyword = harmonize(PURPLE, 0.25);
    let syntax_string = theme.success;
    let syntax_constant = harmonize(PEACH, 0.25);
    let syntax_type = harmonize(YELLOW, 0.22);
    let syntax_preprocessor = harmonize(CYAN, 0.25);

    // 1. Amane theme file in ~/.config/strata/themes/amane.toml
    let amane_toml = format!(
        r#"[theme]
id = "amane"
name = "Amane"
background = "{bg}"
surface = "{surface}"
text = "{fg}"
dim_text = "{dim_text}"
accent = "{accent}"
highlight = "{highlight}"
border = "{border}"
muted = "{muted}"
danger = "{danger}"
syntax_keyword = "{syntax_keyword}"
syntax_string = "{syntax_string}"
syntax_constant = "{syntax_constant}"
syntax_type = "{syntax_type}"
syntax_preprocessor = "{syntax_preprocessor}"
"#,
        bg = hex(theme.background),
        surface = hex(theme.surface),
        fg = hex(theme.text),
        dim_text = hex(theme.secondary_text),
        accent = hex(theme.accent),
        highlight = hex(theme.hover_surface),
        border = hex(theme.border),
        muted = hex(theme.muted_text),
        danger = hex(theme.danger),
        syntax_keyword = hex(syntax_keyword),
        syntax_string = hex(syntax_string),
        syntax_constant = hex(syntax_constant),
        syntax_type = hex(syntax_type),
        syntax_preprocessor = hex(syntax_preprocessor),
    );

    write(&format!("{themes_dir}/amane.toml"), &amane_toml);

    // 2. Documented Matugen dynamic theme file in ~/.config/strata/themes/matugen.toml
    let matugen_toml = format!(
        r#"name = "Matugen"
background = "{bg}"
surface = "{surface}"
text = "{fg}"
accent = "{accent}"
danger = "{danger}"
muted = "{muted}"
highlight = "{highlight}"
border = "{border}"
dim_text = "{dim_text}"
syntax_keyword = "{syntax_keyword}"
syntax_string = "{syntax_string}"
syntax_constant = "{syntax_constant}"
syntax_type = "{syntax_type}"
syntax_preprocessor = "{syntax_preprocessor}"
"#,
        bg = hex(theme.background),
        surface = hex(theme.surface),
        fg = hex(theme.text),
        accent = hex(theme.accent),
        danger = hex(theme.danger),
        muted = hex(theme.muted_text),
        highlight = hex(theme.hover_surface),
        border = hex(theme.border),
        dim_text = hex(theme.secondary_text),
        syntax_keyword = hex(syntax_keyword),
        syntax_string = hex(syntax_string),
        syntax_constant = hex(syntax_constant),
        syntax_type = hex(syntax_type),
        syntax_preprocessor = hex(syntax_preprocessor),
    );

    write(&format!("{themes_dir}/matugen.toml"), &matugen_toml);

    // 3. Documented Omarchy Quattro dynamic theme state in ~/.local/state/omarchy/
    let omarchy_state = format!("{}/.local/state/omarchy/current", home());
    write(&format!("{omarchy_state}/theme.name"), "Amane Dynamic\n");

    let omarchy_colors = format!(
        r#"background = "{bg}"
dark_background = "{surface}"
lighter_background = "{hover}"
foreground = "{fg}"
accent = "{accent}"
selection = "{sel}"
muted = "{border}"
magenta = "{magenta}"
green = "{green}"
orange = "{orange}"
cyan = "{cyan}"
yellow = "{yellow}"
"#,
        bg = hex(theme.background),
        surface = hex(theme.surface),
        hover = hex(theme.hover_surface),
        fg = hex(theme.text),
        accent = hex(theme.accent),
        sel = hex(theme.selected_surface),
        border = hex(theme.border),
        magenta = hex(syntax_keyword),
        green = hex(syntax_string),
        orange = hex(syntax_constant),
        cyan = hex(syntax_preprocessor),
        yellow = hex(syntax_type),
    );

    write(&format!("{omarchy_state}/theme/colors.toml"), &omarchy_colors);

    // 4. Custom style.css for Strata (GTK4 translucency & window borders)
    let reduce_transparency = Settings::read().flag("reduce_transparency");
    let bg_color = if reduce_transparency {
        hex(theme.background)
    } else {
        format!("alpha({}, 0.94)", hex(theme.background))
    };

    let style_content = format!(
        r#"/* Generated by Amane/Swifty — Strata Custom Stylesheet */
window.background,
window.background > box {{
    background-color: {bg_color};
}}

headerbar.browser-header,
.tab-strip {{
    border-color: {border};
}}
"#,
        bg_color = bg_color,
        border = hex(theme.border),
    );

    write(&format!("{strata_dir}/style.css"), &style_content);

    // 5. Ensure settings.toml uses amane theme and current mode (dark/light)
    let settings_path = format!("{strata_dir}/settings.toml");
    update_settings(&settings_path, theme);
}

fn update_settings(path: &str, theme: &Theme) {
    let mode_str = if theme.light { "light" } else { "dark" };
    let mut lines = Vec::new();
    let mut has_theme = false;
    let mut has_mode = false;

    if let Ok(content) = fs::read_to_string(path) {
        for line in content.lines() {
            let trimmed = line.trim();
            if trimmed.starts_with("theme =") || trimmed.starts_with("theme=") {
                lines.push(r#"theme = "amane""#.to_string());
                has_theme = true;
            } else if trimmed.starts_with("mode =") || trimmed.starts_with("mode=") {
                lines.push(format!(r#"mode = "{mode_str}""#));
                has_mode = true;
            } else {
                lines.push(line.to_string());
            }
        }
    }

    if !has_mode {
        lines.insert(0, format!(r#"mode = "{mode_str}""#));
    }
    if !has_theme {
        lines.insert(1, r#"theme = "amane""#.to_string());
    }

    let mut result = lines.join("\n");
    if !result.ends_with('\n') {
        result.push('\n');
    }
    write(path, &result);
}
